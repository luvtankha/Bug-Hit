create table accounts (
    id bigint generated by default as identity primary key,
    email varchar(254) not null unique,
    name varchar(80) not null,
    password_hash varchar(100) not null
);

create table auth_sessions (
    id uuid primary key,
    account_id bigint not null references accounts(id) on delete cascade,
    expires_at timestamp with time zone not null
);
create index auth_sessions_expiry on auth_sessions(expires_at);

create table projects (
    id bigint generated by default as identity primary key,
    project_key varchar(8) not null unique,
    name varchar(100) not null,
    description varchar(1000) not null,
    owner_id bigint not null references accounts(id),
    next_number bigint not null default 1,
    created_at timestamp with time zone not null
);

create table members (
    id bigint generated by default as identity primary key,
    project_id bigint not null references projects(id) on delete cascade,
    account_id bigint not null references accounts(id) on delete cascade,
    role varchar(16) not null check (role in ('ADMIN', 'MANAGER', 'DEVELOPER')),
    unique (project_id, account_id)
);
create index members_account on members(account_id, project_id);

create table issues (
    id bigint generated by default as identity primary key,
    project_id bigint not null references projects(id) on delete cascade,
    issue_key varchar(32) not null unique,
    title varchar(150) not null,
    description varchar(12000) not null,
    issue_type varchar(16) not null check (issue_type in ('BUG', 'TASK', 'STORY')),
    status varchar(16) not null check (status in ('TODO', 'IN_PROGRESS', 'DONE')),
    priority varchar(16) not null check (priority in ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    reporter_id bigint not null references accounts(id),
    assignee_id bigint references accounts(id),
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    version bigint not null default 0
);
create index issues_project_recent on issues(project_id, updated_at desc, id desc);
create index issues_project_status on issues(project_id, status, updated_at desc);
create index issues_project_assignee on issues(project_id, assignee_id);

create table comments (
    id bigint generated by default as identity primary key,
    issue_id bigint not null references issues(id) on delete cascade,
    author_id bigint not null references accounts(id),
    body varchar(4000) not null,
    created_at timestamp with time zone not null
);
create index comments_issue on comments(issue_id, id);

create table attachments (
    id bigint generated by default as identity primary key,
    issue_id bigint not null references issues(id) on delete cascade,
    author_id bigint not null references accounts(id),
    filename varchar(200) not null,
    content_type varchar(40) not null,
    size_bytes integer not null,
    created_at timestamp with time zone not null,
    data bytea not null
);
create index attachments_issue on attachments(issue_id, id);
